/**
 * @file data_store.h
 * @brief 测量数据仓库：把测量核的结果安全地交给交互核使用
 *
 * ─────────────────────────────────────────────────────────────
 * 为什么需要这个模块？（跨核通信的核心难题）
 * ─────────────────────────────────────────────────────────────
 * 本工程双核分工：
 *   Core 1（测量核）以 4000Hz 采样率持续测量，每 25ms 显示子窗写入
 *   "最新测量结果"（40Hz；200ms 块统计另行累计）
 *   Core 0（交互核）以约 5~30Hz 的频率读取它来刷新屏幕
 *
 * 直觉做法是加一把互斥锁（mutex）保护这份数据，但这里有两个问题：
 *   ① 测量核不能被阻塞——250µs 样本周期很紧，等锁会破坏采样时序；
 *   ② 读取的是一整个结构体（当前 17 个字段，共 68 字节），
 *      多字节数据在一次读写中「没有原子性」。
 *
 * 第 ② 点的危害很隐蔽：交互核可能在测量核刚写完电压、还没写电流时
 * 就把整份数据读走，于是得到一个"新电压配旧电流"的错乱组合，
 * 算出来的功率会瞬间跳变——UI 上表现为曲线毛刺，而且极难复现。
 * 这类问题在专业上叫「数据撕裂（data tearing）」。
 *
 * ─────────────────────────────────────────────────────────────
 * 解决方案：seqlock（顺序锁）
 * ─────────────────────────────────────────────────────────────
 * 维护一个序号 seq：
 *   写入前 seq 变奇数（表示"正在写，数据不可信"）
 *   写完   seq 变偶数（表示"数据完整，可以读"）
 *
 * 读取方：读序号 → 拷数据 → 再读序号。
 *   两次序号相同且为偶数 → 说明拷贝期间没有发生写入，数据一定完整；
 *   否则说明撞上了写入过程，直接重读一遍即可。
 *
 * 优点：完全无锁，写方永远不会被读方阻塞（写方优先级第一）；
 *       读方偶尔重读一次，代价只有几十纳秒。
 * 适用前提：写者只有一个（本工程就是测量核），读者可以有多个。
 *
 * 注意：这份数据是「单写者」模型。若将来出现第二个写者，
 *       必须改为互斥锁方案，否则 seqlock 的正确性不再成立。
 */
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "esp_err.h"

/**
 * @brief 实时测量快照
 *
 * 所有字段都是「一次测量得到的一组相关数据」，必须整体一致地读出，
 * 这正是为什么需要上面描述的 seqlock 保护。
 */
typedef struct {
    float voltage_v;     /**< 电压（V） */
    float current_a;     /**< 电流（A） */
    float power_w;       /**< 功率（W） */
    float energy_wh;     /**< 累计电能（Wh，含掉电恢复部分） */
    float temperature_c; /**< 机内温度（℃） */
    float humidity_pct;  /**< 机内相对湿度（%） */
    uint32_t battery_mv; /**< 电池电压（mV），0 表示尚未采集到 */
    uint32_t runtime_s;  /**< 电能统计运行时间（秒，含掉电恢复部分） */
    /* ---- 以下为 v0.2.0 新增（峰值 / 容量 / 告警，追加在尾部保持 seqlock 语义）---- */
    float capacity_ah;   /**< 累计容量（Ah，含掉电恢复部分） */
    float v_max, v_min;  /**< 本次上电电压峰/谷值（V） */
    float i_max, i_min;  /**< 本次上电电流峰/谷值（A） */
    float p_max, p_min;  /**< 本次上电功率峰/谷值（W） */
    uint32_t alert_mask; /**< 当前越限状态位图（DATA_ALERT_*），0=无告警 */
    /* ---- 以下为 v0.5.1 新增（追加在尾部保持 seqlock 语义）---- */
    float soc_temp_c;    /**< 芯片 SOC 结温（℃）；NaN 表示尚未读到有效值。
                         *   与 temperature_c（AHT20 机内环境温度）区分：
                         *   本值反映 ESP32-S3 芯片内部温度传感器读数，
                         *   用于了解主控发热情况，网页端单独展示。 */
} data_store_snapshot_t;

/** 越限告警位（alert_mask） */
#define DATA_ALERT_OVP (1u << 0) /**< 过压 */
#define DATA_ALERT_OCP (1u << 1) /**< 过流 */
#define DATA_ALERT_OPP (1u << 2) /**< 过功率 */
/** 过温（v0.6.5 需求 1）：**双数据源**取最高者，任一 > 65℃ 即置位。
 *  与前三项不同，本项是**硬件保护**性质，不设用户使能开关/阈值——
 *  过温关乎主控寿命与锂电池安全，应始终生效。
 *  数据源（两者任一超限都置位）：
 *    · SOC 结温（soc_temp_c，ESP32-S3 内部温度传感器）——反映主控自身发热；
 *    · AHT20 机内环境温度（temperature_c）——反映机内空气/结构温升。
 *  阈值 65℃ 是"提前预警"与"避免满载正常温升误报"的折中
 *  （S3 结温上限约 105℃，锂电池长期建议 ≤60~65℃）。
 *  判定在测量核块边界做（见 power_measure.c），各自读数无效时不参与判定。 */
#define DATA_ALERT_OTP (1u << 3) /**< 过温（SOC 或机内 >65℃，恒开） */

/**
 * @brief 初始化数据仓库
 *
 * 只做内部状态清零，不分配动态内存（整份数据是静态分配的）。
 *
 * @return ESP_OK 成功
 */
esp_err_t data_store_init(void);

/**
 * @brief 写入最新快照（只能由测量核调用）
 *
 * 本函数不会阻塞，任何时刻调用都能立即返回。
 *
 * @param snapshot 要写入的快照，不可为 NULL
 * @return ESP_OK 成功；ESP_ERR_INVALID_ARG 参数为 NULL
 */
esp_err_t data_store_update(const data_store_snapshot_t *snapshot);

/**
 * @brief 读取最新快照（交互核 / 任意任务可调用）
 *
 * 内部采用 seqlock 重试机制，保证读到的是一份「自洽」的数据，
 * 不会出现新老字段混搭的情况。
 *
 * @param out 输出快照，不可为 NULL
 * @return ESP_OK 成功读到一致数据
 *         ESP_ERR_INVALID_ARG 参数为 NULL
 *         ESP_ERR_INVALID_STATE 尚无任何数据写入过
 *         ESP_ERR_TIMEOUT 连续重试仍未能读到一致数据（理论上极少发生，
 *                         通常意味着写入过于频繁或系统异常）
 */
esp_err_t data_store_get(data_store_snapshot_t *out);

/**
 * @brief 查询累计写入次数
 *
 * 用途：交互核可以据此判断"数据是否有更新"，避免重复处理同一份数据；
 * 也便于在调试时确认测量核是否真的在跑。
 *
 * @return 自初始化以来 data_store_update() 被调用的总次数
 */
uint32_t data_store_update_count(void);
