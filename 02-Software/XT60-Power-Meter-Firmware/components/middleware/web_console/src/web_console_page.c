/**
 * @file web_console_page.c
 * @brief 网页控制台的内嵌单页（深色仪表风，移动端可用，全中文）
 *
 * 设计取舍（配合 web_console.c 文件头阅读）：
 * ① 整页内嵌为 C 字符串常量，不依赖 SPIFFS/分区表——页面随固件一起升级，
 *    不会出现「固件新、页面旧」；改动页面需要重新编译，这是有意的交换。
 * ② 零外部资源：无 CDN、无外链字体、无图片，全部 CSS/JS 内联。
 *    设备可能工作在无外网的现场网络，控制台必须离线可用。
 * ③ 数据通道双保险：优先 WebSocket /ws（约 5Hz 推送），
 *    握手失败或断线时自动退化为每 500ms 轮询 GET /api/state，
 *    并每 5s 尝试重连 WS——两条路用同一套渲染函数，行为一致。
 * ④ 字符串约定：HTML 属性、JS 字符串一律用单引号，避免 C 字符串里
 *    满屏转义的 \"；JS 内需要 JSON 时用 JSON.stringify() 生成，
 *    不手写带双引号的字面量。
 * ⑤ 日志区用 textContent 而不是 innerHTML 渲染，杜绝注入类问题。
 *
 * ⑥ 【v0.5.1 需求】四页签导航条（实时数据 / 波形图 / 设置 / 日志）：
 *    · 实时数据——功率主读数 + 电压/电流/累计电能/累计容量/SOC 温度/
 *      机内温湿度/电池/运行时间。**小数位与设备端屏幕完全一致**：
 *      复用设备端 fmt_val 的「动态小数位」规则（见下方 JS 的 fmtVal，
 *      与 screen_measure.c 的 fmt_val 逐档对齐）；温度 1 位、湿度 0 位
 *      也与设备端小字行一致。告警时顶部红条提示（同设备端横幅）。
 *    · 波形图——canvas 手绘波形，比设备端波形页更完善：
 *      本地按 ~5Hz 累积每帧快照成环形缓冲（3600 点≈12 分钟），
 *      支持 V/I/P 三通道叠加（每通道独立自动量程）、1s~10min 时间窗、
 *      暂停冻结、拖动回看历史（绝对时间冻结，新数据不推动视图）、
 *      十字光标读取任意时刻三通道数值、锁定量程、清空、导出波形 CSV。
 *    · 设置——封装固件端**真实**的设置键（告警阈值与使能、蜂鸣器音量、
 *      屏幕亮度、首页刷新率、WiFi 配网），另保留自定义 JSON 下发，
 *      并提供两类 CSV 导出（设备端分钟级历史 / 网页端 5Hz 波形）。
 *    · 日志——事件日志 + 连接诊断（链路方式、帧数、缓冲点数、最近更新）。
 *
 * ⑦ 波形数据来自**网页本地累积**（不新增固件端波形 API）：页面每收到
 *    一帧快照就存一点，所以打开页面后才开始积累；时间窗上限受浏览器
 *    缓冲长度限制（3600 点 @5Hz ≈ 12 分钟），不足时波形自动从左侧留白。
 */
