/**
 * @file web_console_page.c
 * @brief 网页控制台的内嵌单页（深色仪表风，PC/移动端自适应，全中文）
 *
 * 设计取舍（配合 web_console.c 文件头阅读）：
 * ① 整页内嵌为 C 字符串常量，不依赖 SPIFFS/分区表——页面随固件一起升级，
 *    不会出现「固件新、页面旧」；改动页面需要重新编译，这是有意的交换。
 * ② 零外部资源：无 CDN、无外链字体、无图片，全部 CSS/JS 内联。
 *    设备可能工作在无外网的现场网络，控制台必须离线可用。
 * ③ 数据通道双保险：优先 WebSocket /ws（约 15Hz 推送，v0.6.4 需求 2），握手失败或断线时
 *    自动退化为每 100ms 轮询 GET /api/state，并每 5s 尝试重连 WS——
 *    两条路用同一套渲染函数，行为一致。
 * ④ 字符串约定：HTML 属性、JS 字符串一律用单引号，避免 C 字符串里满屏转义的
 *    \"；JS 内需要 JSON 时用 JSON.stringify() 生成，不手写带双引号的字面量。
 * ⑤ 日志区用 textContent 而不是 innerHTML 渲染，杜绝注入类问题。
 *
 * ⑥ 【v0.6.0 需求】五页签导航（实时数据 / 波形图 / 设置 / API / 日志）：
 *    · 实时数据——按「信息重要性」分四层排版：功率最大（Hero），电压/电流次大，
 *      累计电能/容量/运行时间中等，电池+WiFi 信号再次，SOC 结温/机内温湿度最小。
 *      数值小数位与设备端屏幕完全一致（复用设备端 fmt_val 的动态小数位规则）。
 *    · 波形图——canvas 手绘，网格加密为 8×4（参考设备端 DSO 风格的 4×8 格），
 *      支持 V/I/P 叠加、1s~10min 时间窗、暂停、拖动回看、十字光标、锁定量程；
 *      底部改为三张「通道统计卡」：当前值最大显示，最小/最大/平均用不同颜色区分，
 *      每项都带单位。
 *    · 设置——WiFi 配网（模式切换 + 搜索列表选点 + 密码连接 + 忘记网络）、
 *      告警阈值、显示与声音，所有数值项都配滑动条（与设备端设置页同款交互），
 *      另保留自定义 JSON 下发与两类 CSV 导出。
 *    · API——全部 HTTP/WS 接口的说明文档 + 在线测试台（选方法、填路径与请求体、
 *      即时查看状态码与响应），方便用户自行开发上位机软件或自动化脚本。
 *    · 日志——事件日志 + 连接诊断。
 *
 * ⑦ 波形数据来自网页本地累积（不新增固件端波形 API）：页面每收到一帧快照就存
 *    一点，所以打开页面后才开始积累；缓冲 6000 点 @15Hz ≈ 6.7 分钟。
 *
 * ⑧ 【v0.6.0 性能优化】滚动/触摸页面时波形卡顿的三个根因与对策：
 *    · 每帧全量重绘：改为 requestAnimationFrame 合并 + 脏标记，一帧最多画一次；
 *    · 每秒定时器额外强制重绘：删除，只在收到新数据或交互时重绘；
 *    · 可见点全部 lineTo（6000 点 × 3 通道）：按画布像素宽度做步长抽稀，
 *      并只在「波形页可见」时绘制；图例统计值降频到 2.5Hz 更新。
 */
