/**
 * @file status_led.h
 * @brief 系统运行状态指示灯驱动（SYS_LED / IO39）
 *
 * ─────────────────────────────────────────────────────────────
 * 硬件连接（摘自原理图，务必记住极性！）
 * ─────────────────────────────────────────────────────────────
 *      3V3 ──[ R25 1kΩ ]──[ LED2 阳极→阴极 ]── IO39
 *
 * 电流方向是从 3V3 流向 IO39，所以：
 *      IO39 输出「低电平」→ 有电流 → 灯亮
 *      IO39 输出「高电平」→ 无电流 → 灯灭
 * 这叫「低电平点亮」或「灌电流驱动」。
 * 极性的换算被封装在本驱动内部（见 status_led.c），
 * 上层只需要表达「点亮/熄灭」的意图，不用关心电平高低。
 *
 * ─────────────────────────────────────────────────────────────
 * 本驱动的实现方式：esp_timer 而不是 FreeRTOS 任务
 * ─────────────────────────────────────────────────────────────
 * 让灯闪烁有两种常见写法：
 *
 *   写法一：创建一个任务，循环 vTaskDelay 后翻转电平。
 *           缺点：白白占用一个任务（一个任务要几百字节栈，
 *                 还要参与调度），只为让灯闪，性价比很低。
 *
 *   写法二（本驱动）：用一个 esp_timer 一次定时器，
 *           每次到点由定时器回调翻转电平，并重新安排下一次定时。
 *           好处：不占任务、不占调度时间，代码量也更少。
 *
 * 闪烁的「节奏」被抽象成「步骤序列」：
 *   一个模式 = 一串 (电平, 持续时长) 步骤，走到末尾自动回到开头循环。
 *   这样"慢闪/快闪/双闪"只是不同的步骤序列，驱动逻辑只有一份。
 */
#pragma once

#include "esp_err.h"

/** 指示灯闪烁模式 */
typedef enum {
    STATUS_LED_PATTERN_SOLID = 0, /**< 常亮：系统正在初始化 */
    STATUS_LED_PATTERN_SLOW,      /**< 慢闪 1Hz：正常运行 */
    STATUS_LED_PATTERN_FAST,      /**< 快闪 5Hz：异常（故障） */
    STATUS_LED_PATTERN_DEGRADED,  /**< 双闪 + 长灭：降级运行（部分功能失效） */
} status_led_pattern_t;

/**
 * @brief 初始化指示灯
 *
 * 完成两件事：把 IO39 配成输出，并创建闪烁用的 esp_timer。
 * 初始化后默认使用「常亮」模式（代表系统正在启动）。
 *
 * 注意：本驱动不再自己创建任务，也不再有栈/优先级需要配置——
 *       定时器参数由 Kconfig（组件配置）统一管理。
 *
 * @return ESP_OK 成功
 *         ESP_ERR_INVALID_STATE 重复初始化
 *         ESP_ERR_NO_MEM 定时器创建失败
 */
esp_err_t status_led_init(void);

/**
 * @brief 切换闪烁模式
 *
 * 本函数会立即以新模式的第一个步骤点亮/熄灭灯，不需要等到当前周期结束，
 * 因此在故障报警场景下能第一时间看到反应。
 *
 * 可从任意任务或定时器回调中调用（内部用临界区保护共享状态）。
 *
 * @param pattern 目标模式
 * @return ESP_OK 成功
 *         ESP_ERR_INVALID_ARG 模式非法
 *         ESP_ERR_INVALID_STATE 尚未初始化
 */
esp_err_t status_led_set_pattern(status_led_pattern_t pattern);
