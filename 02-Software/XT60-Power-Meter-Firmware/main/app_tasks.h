/**
 * @file app_tasks.h
 * @brief 应用任务编排与双核分工
 *
 * ─────────────────────────────────────────────────────────────
 * 核分配原则（本工程的关键设计决策）
 * ─────────────────────────────────────────────────────────────
 * ESP32-S3 是双核（Core 0 / Core 1）。ESP-IDF 默认把 WiFi 任务钉在 Core 0，
 * 因此按"通信与交互"和"测量"分开是最省事也最合理的方式：
 *
 *   Core 0（PRO_CPU）—— 交互与通信核
 *       事件总线分发、状态灯、按键、传感器轮询、UI、WiFi、网页控制台
 *
 *   Core 1（APP_CPU）—— 测量核
 *       ADS131M02 采样与功率计算独占此核，避免被通信任务抢占，
 *       保证 4kHz（250µs 周期）采样的时序稳定
 *
 * 为什么不把测量放 Core 0？因为 WiFi 协议栈会周期性占用较多 CPU，
 * 与 4kHz 采样抢核会导致采样抖动，直接影响测量精度。
 * 把两者分开是"用硬件资源换时序确定性"，这是仪器类固件的常规做法。
 *
 * ─────────────────────────────────────────────────────────────
 * 任务编排表（与实现一致）
 * ─────────────────────────────────────────────────────────────
 * | 任务           | 核 | 节奏          | 优先级 | 职责                 |
 * |----------------|----|---------------|--------|----------------------|
 * | pm_sample      | 1  | DRDY 4kHz     | 24     | 采样 + 200ms 块计算  |
 * | task_ui        | 0  | 事件/约 33ms  | 12     | 界面构建与刷新       |
 * | lvgl_port 定时 | 0  | LVGL tick     | 10     | LVGL 定时器/动画     |
 * | event_bus      | 0  | 事件          | 6      | 事件分发             |
 * | pm_aux         | 0  | 2 s           | 5      | 温湿度/电池采集      |
 * | orientation    | 0  | 事件          | 4      | 自动转屏             |
 * | sys_monitor    | 0  | 5 s           | 3      | 系统巡检             |
 * | cfg_save_task  | 0  | 事件（延时落盘）| 2    | 设置持久化           |
 *
 * 优先级遵循「速率单调」原则：周期越短、实时性越高，优先级越高。
 * 注意观察/维护类任务（sys_monitor、cfg_save_task）刻意压低优先级，
 * 绝不能影响业务任务。
 *
 * ─────────────────────────────────────────────────────────────
 * 跨核通信规则
 * ─────────────────────────────────────────────────────────────
 * 允许的两条通道：
 *   ① data_store —— 测量核写、交互核读（seqlock 无锁，见该模块头注释）
 *   ② event_bus  —— 任何核都可发布/订阅
 * 禁止：跨核直接共享可变全局变量。那会导致难以复现的时序 bug。
 */
#pragma once

#include "esp_err.h"

/** 交互与通信核 */
#define APP_CORE_UI      0
/** 测量核（ADS131M02 采样与计算独占） */
#define APP_CORE_MEASURE 1

