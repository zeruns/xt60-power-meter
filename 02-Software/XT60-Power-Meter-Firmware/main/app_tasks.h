/**
 * @file app_tasks.h
 * @brief 应用任务编排与双核分工
 *
 * ─────────────────────────────────────────────────────────────
 * 核分配原则（本工程的关键设计决策）
 * ─────────────────────────────────────────────────────────────
 * ESP32-S3 是双核（Core 0 / Core 1）。ESP-IDF 默认把 WiFi 任务钉在 Core 0，
 * 因此按"通信与交互"和"测量"分开是最省事也最合理的方式：
 *
 *   Core 0（PRO_CPU）—— 交互与通信核
 *       事件总线分发、状态灯、按键、传感器轮询、UI、WiFi、网页控制台
 *
 *   Core 1（APP_CPU）—— 测量核
 *       ADS131M02 采样与功率计算独占此核，避免被通信任务抢占，
 *       保证 1ms 级采样周期的时序稳定
 *
 * 为什么不把测量放 Core 0？因为 WiFi 协议栈会周期性占用较多 CPU，
 * 与 1kHz 采样抢核会导致采样抖动，直接影响测量精度。
 * 把两者分开是"用硬件资源换时序确定性"，这是仪器类固件的常规做法。
 *
 * ─────────────────────────────────────────────────────────────
 * 任务规划表
 * ─────────────────────────────────────────────────────────────
 * | 任务              | 核 | 周期       | 优先级 | 状态   |
 * |-------------------|----|------------|--------|--------|
 * | task_power_sample | 1  | 1 ms       | 22     | 待实现 |
 * | task_power_calc   | 1  | 10 ms      | 18     | 待实现 |
 * | task_ui           | 0  | 事件/33ms  | 12     | 待实现 |
 * | task_input        | 0  | 事件       | 10     | 待实现 |
 * | task_env_sensor   | 0  | 1 s        | 5      | 待实现 |
 * | task_net          | 0  | 事件       | 5      | 待实现 |
 * | task_sys_monitor  | 0  | 5 s        | 3      | 已实现 |
 *
 * 优先级遵循「速率单调」原则：周期越短、实时性要求越高，优先级越高。
 * 注意 sys_monitor 优先级最低——它只是观察者，绝不能影响业务任务。
 *
 * ─────────────────────────────────────────────────────────────
 * 跨核通信规则
 * ─────────────────────────────────────────────────────────────
 * 允许的两条通道：
 *   ① data_store —— 测量核写、交互核读（seqlock 无锁，见该模块头注释）
 *   ② event_bus  —— 任何核都可发布/订阅
 * 禁止：跨核直接共享可变全局变量。那会导致难以复现的时序 bug。
 */
#pragma once

#include "esp_err.h"

/** 交互与通信核 */
#define APP_CORE_UI      0
/** 测量核（ADS131M02 采样与计算独占） */
#define APP_CORE_MEASURE 1

/**
 * @brief 创建全部应用任务
 *
 * 由 app_main() 在系统初始化完成后调用。
 * 每个任务都用 xTaskCreatePinnedToCore 显式绑定 CPU 核，
 * 不依赖调度器"碰运气"分配。
 *
 * @return ESP_OK 成功
 *         ESP_ERR_NO_MEM 任务创建失败（内存不足）
 */
esp_err_t app_tasks_start(void);
