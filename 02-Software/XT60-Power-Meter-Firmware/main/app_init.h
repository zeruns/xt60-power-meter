/**
 * @file app_init.h
 * @brief 系统启动流程：按表初始化各模块，并按"关键 / 非关键"分级容错
 *
 * ─────────────────────────────────────────────────────────────
 * 为什么要用"初始化表 + 分级容错"，而不是一行行 ESP_ERROR_CHECK？
 * ─────────────────────────────────────────────────────────────
 * 最直观的写法是：
 *     ESP_ERROR_CHECK(aht20_init());
 *     ESP_ERROR_CHECK(ads131m02_init());
 *     ...
 * 但 ESP_ERROR_CHECK 失败时会调用 abort() 触发复位，于是：
 *
 *    某模块持续初始化失败 → 复位 → 再失败 → 再复位 → 无限重启
 *
 * 对一台装在用户手里的仪器而言，这是最糟糕的故障模式：
 * 屏幕黑着、灯不亮、无法通过网页升级救回，只能拆机接线重新烧录。
 *
 * 本文件改用「初始化表」，每个模块登记自己的重要程度：
 *   · 关键模块（fault_bit == 0）：失败后系统进入 FAULT 状态，
 *     后续关键模块不再尝试，但"非关键模块"仍然会继续初始化，
 *     保证屏幕 / WiFi 这些"救回通道"尽可能可用。
 *   · 非关键模块（fault_bit != 0）：失败只记一个故障位，
 *     系统降级（DEGRADED）继续运行。
 *
 * 收益：任何单个外设坏掉最多让设备"少一个功能"，
 *       而不会让设备变成一块砖。
 */
#pragma once

#include "esp_err.h"

/**
 * @brief 执行完整启动流程（初始化基础设施 → 外设 → 宣告进入运行态）
 *
 * 本函数内部已包含各模块的初始化与故障登记，main.c 只需调用一次。
 *
 * @return ESP_OK   启动成功（可能处于 RUNNING 或 DEGRADED）
 *         ESP_FAIL 存在关键模块初始化失败（系统已进入 FAULT 状态，
 *                  但不会复位，便于观察与远程救回）
 */
esp_err_t app_init_startup(void);
